// lightThemes lists themes that are light-background themes.
var lightThemes = map[string]bool{
	"tokyonight-light": true,
	"kanagawa-lotus":   true,
	"gruvbox-light":    true,
	"catppuccin-latte": true,
	"bluloco-light":    true,
}

// ThemeEntry represents a single entry in the grouped theme list.
// Group headers have IsHeader=true and Name is the group label.
type ThemeEntry struct {
	Name     string
	IsHeader bool
}

// DefaultThemeName returns the name of the default built-in colorscheme.
func DefaultThemeName() string {
	return "tokyonight"
}

// GroupedThemeEntries returns theme entries grouped by dark/light with headers.
func GroupedThemeEntries() []ThemeEntry {
	var dark, light []string
	for name := range builtinThemes {
		if lightThemes[name] {
			light = append(light, name)
		} else {
			dark = append(dark, name)
		}
	}
	sort.Strings(dark)
	sort.Strings(light)

	entries := []ThemeEntry{{Name: "Dark Themes", IsHeader: true}}
	for _, name := range dark {
		entries = append(entries, ThemeEntry{Name: name})
	}
	entries = append(entries, ThemeEntry{Name: "Light Themes", IsHeader: true})
	for _, name := range light {
		entries = append(entries, ThemeEntry{Name: name})
	}
	return entries
}

// GetTheme returns the built-in ThemeConfig for the given name.
// The second return value is false if the name is not found.
func GetTheme(name string) (config.ThemeConfig, bool) {
	t, ok := builtinThemes[name]
	return t, ok
}
